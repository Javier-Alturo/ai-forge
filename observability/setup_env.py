"""Generate observability/.env with random secrets for the local LangFuse stack.

    python observability/setup_env.py                 # create observability/.env (never overwrites)
    python observability/setup_env.py --write-app-env # also add LANGFUSE_* keys to the repo .env

Secrets are random per machine and live only in git-ignored .env files.
"""

from __future__ import annotations

import argparse
import secrets
from pathlib import Path

HERE = Path(__file__).resolve().parent
COMPOSE_ENV = HERE / ".env"
APP_ENV = HERE.parent / ".env"
HOST = "http://localhost:3000"


def generate() -> dict[str, str]:
    return {
        "POSTGRES_PASSWORD": secrets.token_hex(16),
        "CLICKHOUSE_PASSWORD": secrets.token_hex(16),
        "REDIS_PASSWORD": secrets.token_hex(16),
        "MINIO_ROOT_PASSWORD": secrets.token_hex(16),
        "NEXTAUTH_SECRET": secrets.token_hex(32),
        "SALT": secrets.token_hex(32),
        "ENCRYPTION_KEY": secrets.token_hex(32),  # must be 64 hex chars
        "LANGFUSE_PUBLIC_KEY": "pk-lf-" + secrets.token_hex(16),
        "LANGFUSE_SECRET_KEY": "sk-lf-" + secrets.token_hex(16),
        "LANGFUSE_ADMIN_EMAIL": "admin@langfuse.local",
        "LANGFUSE_ADMIN_PASSWORD": secrets.token_urlsafe(18),
    }


def read_env(path: Path) -> dict[str, str]:
    values = {}
    if path.exists():
        for line in path.read_text(encoding="utf-8").splitlines():
            if "=" in line and not line.lstrip().startswith("#"):
                key, _, value = line.partition("=")
                values[key.strip()] = value.strip()
    return values


def app_env_lines(compose_values: dict[str, str]) -> list[str]:
    return [
        "LANGFUSE_ENABLED=1",
        f"LANGFUSE_HOST={HOST}",
        f"LANGFUSE_PUBLIC_KEY={compose_values['LANGFUSE_PUBLIC_KEY']}",
        f"LANGFUSE_SECRET_KEY={compose_values['LANGFUSE_SECRET_KEY']}",
    ]


def write_compose_env(path: Path = COMPOSE_ENV) -> tuple[dict[str, str], bool]:
    """Create the compose .env if missing. Returns (values, created)."""
    if path.exists():
        return read_env(path), False
    values = generate()
    body = "# Generated by observability/setup_env.py — local secrets, never commit.\n"
    body += "".join(f"{k}={v}\n" for k, v in values.items())
    path.write_text(body, encoding="utf-8")
    return values, True


def add_to_app_env(lines: list[str], path: Path = APP_ENV) -> list[str]:
    """Append LANGFUSE_* lines whose keys are not already in the app .env. Returns lines added."""
    existing = read_env(path)
    missing = [ln for ln in lines if ln.split("=", 1)[0] not in existing]
    if missing:
        with path.open("a", encoding="utf-8") as f:
            f.write("\n# --- LangFuse local (observability/) ---\n" + "\n".join(missing) + "\n")
    return missing


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write-app-env", action="store_true", help="append LANGFUSE_* to the repo .env")
    args = parser.parse_args(argv)

    values, created = write_compose_env()
    print(("Created " if created else "Kept existing ") + str(COMPOSE_ENV))
    lines = app_env_lines(values)
    if args.write_app_env:
        added = add_to_app_env(lines)
        print(f"Added {len(added)} LANGFUSE_* line(s) to {APP_ENV}" if added else "App .env already configured.")
    else:
        print("Add these lines to the repo .env (or rerun with --write-app-env):")
        print("\n".join(line.split("=", 1)[0] + "=..." for line in lines))
    print(f"UI: {HOST}  user: {values['LANGFUSE_ADMIN_EMAIL']}  password: see {COMPOSE_ENV.name}")


if __name__ == "__main__":
    main()
